const getCopy = (locale = "en") => COPY[locale] || COPY.en;

export function buildVisualTrackingHubMetadata(locale, url, count, languages) {
  const copy = getCopy(locale);
  const title = `${copy.title} | SkillDrills`;
  return {
    title,
    description: copy.description.replace("15", String(count)),
    keywords: copy.keywords,
    robots: { index: true, follow: true },
    alternates: { canonical: url, languages },
    openGraph: { title, description: copy.description, url, siteName: "SkillDrills", type: "website", locale: copy.locale, images: [{ url: "https://skilldrills.online/icons/icon-512x512.png", width: 512, height: 512, alt: copy.title }] },
    twitter: { card: "summary_large_image", title, description: copy.description, images: ["https://skilldrills.online/icons/icon-512x512.png"] },
    other: { "og:locale": copy.locale, "skilldrills:drill-count": String(count) }
  };
}

